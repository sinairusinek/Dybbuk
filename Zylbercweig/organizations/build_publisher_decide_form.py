SCRIPT = """
<script>
(function () {
  "use strict";
  var COLL = "publisher_decisions";
  var db = null, state = Object.create(null);
  var bars = Array.prototype.slice.call(document.querySelectorAll(".acts"));
  function card(el) { return el.closest(".card"); }
  function paint(cid) {
    var bar = document.querySelector('.acts[data-cid="' + CSS.escape(cid) + '"]');
    if (!bar) return;
    var st = state[cid] || {};
    bar.querySelectorAll("button[data-v]").forEach(function (b) {
      b.setAttribute("aria-pressed", String(b.dataset.v === st.decision));
    });
    var n = bar.querySelector(".note");
    if (n && document.activeElement !== n) n.value = st.note || "";
    card(bar).classList.toggle("done", !!st.decision);
  }
  function progress() {
    var d = bars.filter(function (b) { var s = state[b.dataset.cid]; return s && s.decision; }).length;
    var el = document.getElementById("progress");
    if (el) el.innerHTML = "<b>" + d + "</b> of <b>" + bars.length + "</b> decided" +
      (d === bars.length && bars.length ? " — all done" : "");
  }
  function ro() { var w = document.getElementById("readonly"); if (w) w.hidden = false; }
  function save(cid) {
    if (!db) return;
    var st = state[cid] || {}, ref = db.collection(COLL).doc(cid);
    (st.decision
      ? ref.set({ decision: st.decision, note: st.note || "", at: new Date().toISOString() })
      : ref.delete()).catch(ro);
  }
  function set(cid, decision, note) {
    var st = state[cid] || (state[cid] = {});
    if (decision !== undefined) st.decision = decision || "";
    if (note !== undefined) st.note = note;
    if (!st.decision) delete state[cid];
    paint(cid); progress(); save(cid);
  }
  document.addEventListener("click", function (ev) {
    var b = ev.target.closest("button");
    if (!b) return;
    if (b.dataset.v) {
      var cid = b.closest(".acts").dataset.cid;
      var cur = (state[cid] || {}).decision;
      set(cid, cur === b.dataset.v ? "" : b.dataset.v);
    } else if (b.id === "jump") {
      var next = bars.filter(function (x) { return !(state[x.dataset.cid] || {}).decision; })[0];
      if (next) card(next).scrollIntoView({ behavior: "smooth", block: "center" });
    } else if (b.id === "toggledone") {
      var on = b.getAttribute("aria-pressed") !== "true";
      b.setAttribute("aria-pressed", String(on));
      b.textContent = on ? "Show decided" : "Hide decided";
      document.querySelectorAll(".card").forEach(function (c) {
        if (c.classList.contains("done")) c.hidden = on;
      });
    }
  });
  document.addEventListener("change", function (ev) {
    var n = ev.target.closest(".note");
    if (!n) return;
    var cid = n.closest(".acts").dataset.cid;
    if (!(state[cid] || {}).decision) return;
    set(cid, undefined, n.value);
  });
  progress();
  claude.use("db").then(function (d) {
    if (!d) { ro(); return; }
    db = d;
    db.collection(COLL).onSnapshot(function (snap) {
      var seen = Object.create(null);
      snap.docs.forEach(function (doc) {
        var v = doc.data() || {};
        seen[doc.id] = 1;
        state[doc.id] = { decision: v.decision || "", note: v.note || "" };
      });
      Object.keys(state).forEach(function (k) { if (!seen[k]) delete state[k]; });
      bars.forEach(function (b) { paint(b.dataset.cid); });
      progress();
    }, ro);
  }).catch(ro);
})();
</script>"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()
    rows = json.loads(DATA.read_text(encoding="utf-8"))
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(rows), encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size // 1024} KB, {len(rows)} clusters)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
