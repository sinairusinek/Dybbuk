def e(s) -> str:
    return html.escape(str(s or ""), quote=True)


def dir_span(s: str, cls: str = "") -> str:
    """Wrap so Hebrew and Latin each read in their own direction."""
    c = ("yi " + cls).strip() if HEBREW.search(s or "") else ("lat " + cls).strip()
    return f'<span class="{c}">{e(s)}</span>'


def mark(sentence: str, name: str) -> str:
    """Show the sentence with the organization name picked out."""
    s, n = sentence or "", (name or "").strip()
    if not n or n not in s:
        return e(s)
    i = s.index(n)
    return e(s[:i]) + "<mark>" + e(n) + "</mark>" + e(s[i + len(n):])


