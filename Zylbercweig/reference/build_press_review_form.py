#!/usr/bin/env python3
"""Generate the Galron press review form from the CURRENT matcher output.

Why this exists: round 1's form was hand-built, so when both matcher defects
were fixed the form kept showing the pre-fix Tier C and E tables -- rows that no
longer exist (Tier E went 43 -> 19). The handoff's first instruction was to
regenerate it. A committed generator means that never becomes a manual step
again.

Reads galron_press_match_review.tsv and emits ONLY the rows still undecided,
grouped by tier, with the Galron evidence each decision needs (place, years,
language, depository, scan link) and the matcher's own signals. Where several
Zylbercweig orgs claim the SAME Galron paper, the claimants are shown together:
that is the contested-group structure, and those sets double as within-corpus
merge candidates.

Output: press_review_form.html (self-contained, no network use).

Usage:
    python3 build_press_review_form.py [--out PATH] [--include-weak]
"""
from __future__ import annotations

import argparse
import csv
import html
import io
from collections import defaultdict
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent
REVIEW = HERE / "galron_press_match_review.tsv"

TIER_ORDER = ["A-exact-skeleton", "B-both-agree", "C-phonetic-plus",
              "D-partial-both", "E-phonetic-only", "F-weak-signal", ""]
TIER_NOTE = {
    "A-exact-skeleton": "Skeletons identical. Strong, but the skeleton drops vowels — "
                        "it has collapsed distinct titles before (התקופה/השקפה, "
                        "באָברויסקער/בריסקער), so check place and years on short "
                        "Hebrew titles and on anything toponym-derived.",
    "B-both-agree":     "Skeleton and phonetic key both agree.",
    "C-phonetic-plus":  "Phonetic agreement plus a supporting signal. The short generic "
                        "titles live here (Vokhnblat, Zhurnal, Fraynd, Kultur) — location "
                        "usually decides them.",
    "D-partial-both":   "Partial agreement on both keys.",
    "E-phonetic-only":  "Phonetic only, no skeleton agreement. Expect mostly REJECT. The "
                        "language gate already cleared 24 of the original 43.",
    "F-weak-signal":    "Weakest signal that still blocked.",
    "":                 "No tier assigned (STRONG/WEAK band).",
}
SIGNAL_COLS = ["signal", "phonetic", "score", "place_agree", "same_script",
               "qualifier_clash", "place_conflict", "span_check", "language_ok",
               "zyl_is_firm"]


def read_rows(path: Path) -> list[dict]:
    csv.field_size_limit(10 ** 9)
    raw = path.read_text(encoding="utf-8")
    return list(csv.DictReader(io.StringIO(raw), delimiter="\t"))


def entity_of(r: dict) -> str:
    cid = (r.get("cluster_id") or "").strip()
    return cid if cid else f"db{(r.get('db_id') or '').strip()}"


def e(s: str | None) -> str:
    return html.escape((s or "").strip())


def signal_chips(r: dict) -> str:
    out = []
    for c in SIGNAL_COLS:
        v = (r.get(c) or "").strip()
        if not v or v == "-":
            continue
        cls = "chip"
        if c in ("qualifier_clash", "place_conflict") or v == "N":
            cls += " bad"
        elif (c == "span_check" and v.startswith("apart")):
            cls += " warn"
        elif v in ("Y", "overlap", "near") or c in ("signal", "phonetic", "score"):
            cls += " good"
        out.append(f'<span class="{cls}">{e(c)}={e(v)}</span>')
    return " ".join(out)


def render(rows: list[dict], include_weak: bool) -> str:
    open_rows = [r for r in rows
                 if not (r.get("decision") or "").strip()
                 and (include_weak or r.get("band") == "REVIEW")]
    decided = [r for r in rows if (r.get("decision") or "").strip()]

    by_galron: dict[str, list[dict]] = defaultdict(list)
    for r in open_rows:
        by_galron[(r.get("galron_row_id") or "").strip()].append(r)
    contested = {k: v for k, v in by_galron.items() if len(v) > 1}
    contested_rows = {id(r) for v in contested.values() for r in v}

    by_tier: dict[str, list[dict]] = defaultdict(list)
    for r in open_rows:
        by_tier[(r.get("tier") or "").strip()].append(r)

    from collections import Counter
    dec_counts = Counter((r.get("decision") or "").strip() for r in decided)

    P: list[str] = []
    P.append(f"""<!-- generated by build_press_review_form.py on {date.today()} -->
<title>Galron press review — open rows</title>
<style>
  :root {{
    --bg:#fbfaf8; --fg:#1b1a17; --muted:#6b6660; --line:#e2ded7; --card:#fff;
    --good:#2b6b4f; --goodbg:#e8f3ed; --warn:#8a5a1a; --warnbg:#fbf0dd;
    --bad:#8c2f2a; --badbg:#f8e8e6; --accent:#3a5a8c; --accentbg:#e9eef6;
  }}
  :root:not([data-theme="light"]) {{ }}
  @media (prefers-color-scheme: dark) {{
    :root:not([data-theme="light"]) {{
      --bg:#17171a; --fg:#e8e6e1; --muted:#9a948c; --line:#32312f; --card:#1f1f22;
      --good:#7fc6a3; --goodbg:#1c2f26; --warn:#d9a44f; --warnbg:#332816;
      --bad:#e08a84; --badbg:#331e1d; --accent:#8fabd8; --accentbg:#1d2535;
    }}
  }}
  :root[data-theme="dark"] {{
    --bg:#17171a; --fg:#e8e6e1; --muted:#9a948c; --line:#32312f; --card:#1f1f22;
    --good:#7fc6a3; --goodbg:#1c2f26; --warn:#d9a44f; --warnbg:#332816;
    --bad:#e08a84; --badbg:#331e1d; --accent:#8fabd8; --accentbg:#1d2535;
  }}
  body {{ background:var(--bg); color:var(--fg); margin:0;
    font:15px/1.55 -apple-system,BlinkMacSystemFont,"Segoe UI",system-ui,sans-serif; }}
  .wrap {{ max-width:1080px; margin:0 auto; padding:32px 20px 80px; }}
  h1 {{ font-size:25px; margin:0 0 6px; letter-spacing:-.01em; }}
  .sub {{ color:var(--muted); margin:0 0 26px; }}
  h2 {{ font-size:18px; margin:40px 0 4px; }}
  .tiernote {{ color:var(--muted); font-size:13.5px; margin:0 0 16px; max-width:76ch; }}
  .stats {{ display:flex; flex-wrap:wrap; gap:8px; margin:0 0 10px; }}
  .stat {{ background:var(--card); border:1px solid var(--line); border-radius:8px;
    padding:7px 11px; font-size:13px; }}
  .stat b {{ font-size:15px; }}
  .row {{ background:var(--card); border:1px solid var(--line); border-radius:10px;
    padding:13px 15px; margin:0 0 10px; }}
  .row.contested {{ border-left:3px solid var(--accent); }}
  .pair {{ display:grid; grid-template-columns:1fr auto 1fr; gap:12px; align-items:start; }}
  @media (max-width:720px) {{ .pair {{ grid-template-columns:1fr; }} }}
  .side .lbl {{ font-size:11px; text-transform:uppercase; letter-spacing:.07em;
    color:var(--muted); margin-bottom:2px; }}
  .ttl {{ font-size:16px; font-weight:600; }}
  .rtl {{ direction:rtl; unicode-bidi:plaintext; }}
  .meta {{ color:var(--muted); font-size:13px; margin-top:3px; }}
  .vs {{ color:var(--muted); font-size:12px; padding-top:16px; }}
  .chips {{ margin-top:9px; display:flex; flex-wrap:wrap; gap:5px; }}
  .chip {{ font-size:11.5px; padding:2px 7px; border-radius:20px;
    background:var(--bg); border:1px solid var(--line); color:var(--muted); }}
  .chip.good {{ background:var(--goodbg); color:var(--good); border-color:transparent; }}
  .chip.warn {{ background:var(--warnbg); color:var(--warn); border-color:transparent; }}
  .chip.bad  {{ background:var(--badbg);  color:var(--bad);  border-color:transparent; }}
  .ent {{ font-family:ui-monospace,SFMono-Regular,Menlo,monospace; font-size:12px;
    color:var(--muted); }}
  .flag {{ display:inline-block; font-size:11.5px; padding:2px 8px; border-radius:20px;
    background:var(--accentbg); color:var(--accent); margin-bottom:8px; }}
  a {{ color:var(--accent); }}
  .ask {{ background:var(--accentbg); border:1px solid var(--line); border-radius:10px;
    padding:14px 16px; margin:22px 0 0; font-size:14px; }}
</style>
<div class="wrap">
<h1>Galron press review — the open rows</h1>
<p class="sub">Generated from <code>galron_press_match_review.tsv</code> as it
stands today, so every row below still exists in the current matcher output.
Decided rows are omitted.</p>
<div class="stats">
  <div class="stat"><b>{len(open_rows)}</b> open</div>
  <div class="stat"><b>{len(decided)}</b> decided</div>
  <div class="stat"><b>{len(contested)}</b> contested papers</div>""")
    for d in ("CONFIRM", "REJECT", "RESEARCH_FURTHER", "NOT_A_NEWSPAPER"):
        if dec_counts.get(d):
            P.append(f'  <div class="stat">{d.title().replace("_"," ")} <b>{dec_counts[d]}</b></div>')
    P.append("</div>")

    P.append("""<div class="ask"><b>What a decision means.</b>
    <b>CONFIRM</b> — this Zylbercweig org is the paper Galron lists.
    <b>REJECT</b> — different publications.
    <b>RESEARCH_FURTHER</b> — the title matches but something (usually the years)
    needs a source first.
    <b>NOT_A_NEWSPAPER</b> — the Zylbercweig side is not a serial at all.
    Nothing of Galron's is minted: his list is a reference, not a source of
    organizations.</div>""")

    for tier in TIER_ORDER:
        group = by_tier.get(tier, [])
        if not group:
            continue
        label = tier or "untiered"
        P.append(f'<h2>{e(label)} <span style="color:var(--muted);font-weight:400">'
                 f'— {len(group)} open</span></h2>')
        P.append(f'<p class="tiernote">{e(TIER_NOTE.get(tier, ""))}</p>')
        group.sort(key=lambda r: ((r.get("galron_row_id") or ""), entity_of(r)))
        for r in group:
            cls = "row contested" if id(r) in contested_rows else "row"
            P.append(f'<div class="{cls}">')
            gid = (r.get("galron_row_id") or "").strip()
            if id(r) in contested_rows:
                n = len(by_galron[gid])
                P.append(f'<div class="flag">contested — {n} Zylbercweig orgs claim '
                         f'this paper; the claimant set is also a merge candidate</div>')
            zyl = (r.get("matched_on") or r.get("db_name")
                   or r.get("db_name_yiddish") or "").strip()
            zmeta = " · ".join(x for x in [
                (r.get("org_type") or "").strip(),
                (r.get("db_address") or "").strip(),
                f"dates {(r.get('db_dates') or '').strip()}" if (r.get("db_dates") or "").strip() else "",
            ] if x)
            gmeta = " · ".join(x for x in [
                (r.get("galron_place") or "").strip(),
                (r.get("galron_years") or "").strip(),
                (r.get("galron_language") or "").strip(),
                (r.get("galron_depository") or "").strip(),
            ] if x)
            url = (r.get("galron_scan_url") or "").strip().replace("&amp;", "&")
            link = f' · <a href="{e(url)}" rel="noreferrer">scan</a>' if url.startswith("http") else ""
            P.append(f"""<div class="pair">
  <div class="side">
    <div class="lbl">Zylbercweig</div>
    <div class="ttl rtl">{e(zyl) or "<em>—</em>"}</div>
    <div class="meta">{e(zmeta)}</div>
    <div class="ent">{e(entity_of(r))}</div>
  </div>
  <div class="vs">vs</div>
  <div class="side">
    <div class="lbl">Galron</div>
    <div class="ttl rtl">{e(r.get("galron_title"))}</div>
    <div class="meta">{e(gmeta)}{link}</div>
    <div class="ent">{e(gid)}</div>
  </div>
</div>""")
            chips = signal_chips(r)
            if chips:
                P.append(f'<div class="chips">{chips}</div>')
            P.append("</div>")

    P.append("</div>")
    return "\n".join(P)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(HERE / "press_review_form.html"))
    ap.add_argument("--include-weak", action="store_true",
                    help="also include the WEAK band (192 rows), not just REVIEW")
    a = ap.parse_args()
    rows = read_rows(REVIEW)
    out = Path(a.out)
    out.write_text(render(rows, a.include_weak), encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
