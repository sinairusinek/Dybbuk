#!/usr/bin/env python3
"""Generate the Galron press review form from the CURRENT matcher output.

Why this exists: round 1's form was hand-built, so when both matcher defects
were fixed the form kept showing the pre-fix Tier C and E tables -- rows that no
longer exist (Tier E went 43 -> 19). The handoff's first instruction was to
regenerate it. A committed generator means that never becomes a manual step
again.

Reads galron_press_match_review.tsv and emits ONLY the rows still undecided,
grouped by tier, with the Galron evidence each decision needs (place, years,
language, depository, scan link) and the matcher's own signals. Where several
Zylbercweig orgs claim the SAME Galron paper, the claimants are shown together:
that is the contested-group structure, and those sets double as within-corpus
merge candidates.

Output: press_review_form.html — an interactive form. Decisions are saved to the
artifact's `db` (one document per row, keyed `<entity>__<galron_row_id>`), so
they survive reloads and can be read back with the Artifact tool's `read_db` and
written into the review TSV by `apply_form_decisions.py`.

Usage:
    python3 build_press_review_form.py [--out PATH] [--include-weak]
"""
