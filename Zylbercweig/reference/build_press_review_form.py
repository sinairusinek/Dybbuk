def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(HERE / "press_review_form.html"))
    ap.add_argument("--include-weak", action="store_true",
                    help="also include the WEAK band (192 rows), not just REVIEW")
    a = ap.parse_args()
    rows = read_rows(REVIEW)
    out = Path(a.out)
    out.write_text(render(rows, a.include_weak), encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
