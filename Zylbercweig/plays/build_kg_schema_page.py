"""Generate the schema page for the Zylbercweig Plays KG.

The KG is the largest of the project's three graphs and, until now, the only one
whose schema was documented nowhere: 42 relation types and 21 edge columns that
existed solely as whatever build_kg.py happened to emit. This script derives the
schema from the built graph itself — kg/nodes.tsv and kg/edges.tsv — so the page
reports the schema as built rather than as remembered.

Written to follow YiDraCor/code/build_schema_tab.py, which documents the smaller
Lateiner/Hurwitz graph, and to share its two safety properties:

  * it rewrites only the block between the SCHEMA markers, leaving the page's
    prose alone;
  * it RAISES on a node type, relation or column that has no curated note, so a
    new field cannot silently vanish from the documentation. A new entry appears
    with a blank meaning rather than being dropped.

The vocabularies (match_status, confidence, source_layer, date_precision,
extraction_model) are read off the data, so a new value shows up on its own.

Run after every build_kg.py run:

    python3.11 build_kg_schema_page.py     # from Zylbercweig/plays/
"""
