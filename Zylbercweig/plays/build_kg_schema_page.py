def main() -> int:
    nodes = _rows(NODES_TSV)
    edges = _rows(EDGES_TSV)
    block = build_block(nodes, edges)

    if PAGE.exists():
        page = PAGE.read_text(encoding="utf-8")
        if BEGIN not in page or END not in page:
            raise SystemExit(
                f"{PAGE.name} exists but has no SCHEMA markers — refusing to "
                f"overwrite a hand-made page. Add {BEGIN} / {END} around the "
                f"generated block, or delete the file to regenerate the shell."
            )
        head = page[:page.index(BEGIN)]
        tail = page[page.index(END) + len(END):]
        PAGE.write_text(head + block + tail, encoding="utf-8")
        how = "block rewritten"
    else:
        PAGE.write_text(
            SHELL.format(block=block, graph=GRAPH_URL, sister=SISTER_URL),
            encoding="utf-8")
        how = "page created"

    n_rel = len({e["edge_type"] for e in edges})
    n_kind = len({n["node_type"] for n in nodes})
    print(f"plays KG schema page: {how} — {len(nodes):,} nodes, "
          f"{len(edges):,} edges, {n_kind} node types, {n_rel} relations "
          f"-> {PAGE}")
    print(f"live: {LIVE_URL}")
    return 0


