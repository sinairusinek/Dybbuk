def _rows(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))


def esc(s) -> str:
    return html.escape(str(s if s is not None else ""))


def _fmt(n: int) -> str:
    return f"{n:,}"


def _check_covered(label: str, seen, noted, *, required: bool) -> dict:
    """Return {key: note}, raising when a key has no curated note.

    `required=True` means every key must be documented (node types, columns);
    a relation may legitimately have no note when its name says it all, so for
    those we only record what exists.
    """
    missing = [k for k in seen if k not in noted]
    if required and missing:
        raise SystemExit(
            f"{label}: no curated note for {missing!r}.\n"
            f"Add it to the relevant *_NOTE table in {Path(__file__).name} "
            f"(a blank string is fine) so the schema page documents it rather "
            f"than dropping it silently."
        )
    return {k: noted.get(k, "") for k in seen}


def build_block(nodes: list[dict], edges: list[dict]) -> str:
    node_cols = list(nodes[0].keys())
    edge_cols = list(edges[0].keys())
    by_id = {n["node_id"]: n for n in nodes}

    kinds = Counter(n["node_type"] for n in nodes)
    rels = Counter(e["edge_type"] for e in edges)

    # Coverage gates: a new column or kind must be documented, not dropped.
    _check_covered("node column", node_cols, NODE_FIELD_NOTE, required=True)
    _check_covered("edge column", edge_cols, EDGE_FIELD_NOTE, required=True)
    _check_covered("node type", kinds, KIND_NOTE, required=True)
    rel_notes = _check_covered("relation", rels, REL_NOTE, required=False)

    # endpoint kinds, per relation, off the data
    endpoints: dict[str, Counter] = defaultdict(Counter)
    for e in edges:
        s, t = by_id.get(e["source_id"]), by_id.get(e["target_id"])
        if s and t:
            endpoints[e["edge_type"]][(s["node_type"], t["node_type"])] += 1

    # which columns each relation actually uses — the schema is sparse by design
    rel_fields: dict[str, set] = defaultdict(set)
    for e in edges:
        for k, v in e.items():
            if str(v).strip():
                rel_fields[e["edge_type"]].add(k)

    fill_n = {c: sum(1 for n in nodes if str(n[c]).strip()) for c in node_cols}
    fill_e = {c: sum(1 for e in edges if str(e[c]).strip()) for c in edge_cols}

    vocabs = {
        "node_type": Counter(n["node_type"] for n in nodes),
        "ext_ref_type": Counter(n["ext_ref_type"] for n in nodes
                                if n["ext_ref_type"].strip()),
        "match_status": Counter(e["match_status"] for e in edges),
        "confidence": Counter(e["confidence"] for e in edges),
        "source_layer": Counter(e["source_layer"] for e in edges),
        "date_precision": Counter(e["date_precision"] for e in edges
                                  if e["date_precision"].strip()),
        "extraction_model": Counter(e["extraction_model"] for e in edges),
        "review_status": Counter(e["review_status"] for e in edges),
        "attribution": Counter(e["attribution"] for e in edges
                               if e["attribution"].strip()),
    }

    layers_n = Counter(n["source_layer"] for n in nodes)
    out: list[str] = [BEGIN]
    a = out.append

    a('<section class="s">')
    a("<h2>In numbers</h2>")
    a('<p class="note">Everything on this page is read off '
      "<code>kg/nodes.tsv</code> and <code>kg/edges.tsv</code> by "
      "<code>build_kg_schema_page.py</code>. If a figure here is wrong, the "
      "graph says so too.</p>")
    a('<div class="stats">')
    for label, val in (("nodes", len(nodes)), ("edges", len(edges)),
                       ("node types", len(kinds)), ("relations", len(rels)),
                       ("layers", len(layers_n))):
        a(f'<div class="stat"><b>{_fmt(val)}</b><span>{esc(label)}</span></div>')
    a("</div>")

    a("<h3>Layers</h3>")
    a('<p class="note">Four layer modules share one graph; every row carries '
      "its <code>source_layer</code>, so a layer can be rebuilt or viewed "
      "alone.</p>")
    a("<table><thead><tr><th>layer</th><th>nodes</th><th>edges</th>"
      "<th>module</th></tr></thead><tbody>")
    mods = {"plays": "build_kg.py (play facts)", "bio": "kg_bio.py",
            "orgrel": "kg_orgrel.py", "mentions": "kg_mentions.py"}
    for lay, cnt in layers_n.most_common():
        a(f"<tr><td><code>{esc(lay)}</code></td><td>{_fmt(cnt)}</td>"
          f"<td>{_fmt(vocabs['source_layer'].get(lay, 0))}</td>"
          f"<td>{esc(mods.get(lay, ''))}</td></tr>")
    a("</tbody></table>")
    a("</section>")

    # ---- node kinds
    a('<section class="s">')
    a(f"<h2>Node types <span class='c'>{len(kinds)}</span></h2>")
    a("<table><thead><tr><th>type</th><th>n</th><th>what it is</th>"
      "</tr></thead><tbody>")
    for k in [k for k in KIND_ORDER if k in kinds] + \
             [k for k in kinds if k not in KIND_ORDER]:
        a(f"<tr><td><code>{esc(k)}</code></td><td>{_fmt(kinds[k])}</td>"
          f"<td>{esc(KIND_NOTE.get(k, ''))}</td></tr>")
    a("</tbody></table>")

    a("<h3>Node columns</h3>")
    a('<p class="note">“filled” counts rows where the column is non-empty. A '
      "sparse column is normal: the schema is one table for seven kinds.</p>")
    a("<table><thead><tr><th>column</th><th>filled</th><th>meaning</th>"
      "</tr></thead><tbody>")
    for c in node_cols:
        pct = 100 * fill_n[c] / len(nodes)
        a(f"<tr><td><code>{esc(c)}</code></td>"
          f"<td>{_fmt(fill_n[c])} <span class='c'>{pct:.0f}%</span></td>"
          f"<td>{esc(NODE_FIELD_NOTE.get(c, ''))}</td></tr>")
    a("</tbody></table>")
    a("</section>")

    # ---- relations
    a('<section class="s">')
    a(f"<h2>Relations <span class='c'>{len(rels)}</span></h2>")
    a('<p class="note">Endpoint types and counts are derived from the edges '
      "themselves; a relation with more than one endpoint shape lists each.</p>")
    a("<table><thead><tr><th>relation</th><th>n</th><th>endpoints</th>"
      "<th>what it asserts</th></tr></thead><tbody>")
    for r, n in rels.most_common():
        shapes = " · ".join(
            f"{s}&nbsp;&rarr;&nbsp;{t} <span class='c'>{_fmt(c)}</span>"
            for (s, t), c in endpoints[r].most_common())
        a(f"<tr><td><code>{esc(r)}</code></td><td>{_fmt(n)}</td>"
          f"<td>{shapes}</td><td>{esc(rel_notes.get(r, ''))}</td></tr>")
    a("</tbody></table>")

    a("<h3>Edge columns</h3>")
    a("<table><thead><tr><th>column</th><th>filled</th><th>meaning</th>"
      "</tr></thead><tbody>")
    for c in edge_cols:
        pct = 100 * fill_e[c] / len(edges)
        a(f"<tr><td><code>{esc(c)}</code></td>"
          f"<td>{_fmt(fill_e[c])} <span class='c'>{pct:.0f}%</span></td>"
          f"<td>{esc(EDGE_FIELD_NOTE.get(c, ''))}</td></tr>")
    a("</tbody></table>")
    a("</section>")

    # ---- vocabularies
    a('<section class="s">')
    a("<h2>Vocabularies</h2>")
    a('<p class="note">Read off the data, so a newly introduced value appears '
      "here on its own.</p>")
    for name, c in vocabs.items():
        if not c:
            continue
        a(f"<h3><code>{esc(name)}</code></h3>")
        if VOCAB_NOTE.get(name):
            a(f"<p class='note'>{esc(VOCAB_NOTE[name])}</p>")
        a('<p class="vals">' + " ".join(
            f"<span class='pill'><code>{esc(k)}</code> {_fmt(v)}</span>"
            for k, v in c.most_common()) + "</p>")
    a("</section>")

    # ---- id conventions
    a('<section class="s">')
    a("<h2>Node id conventions</h2>")
    a("<table><thead><tr><th>pattern</th><th>meaning</th></tr></thead><tbody>")
    for pat, mean in ID_CONVENTIONS:
        a(f"<tr><td><code>{esc(pat)}</code></td><td>{esc(mean)}</td></tr>")
    a("</tbody></table>")
    a('<p class="note"><b>Edge ids are not stable.</b> '
      "<code>edge_id</code> renumbers on every <code>build_kg.py</code> run; "
      "reference an edge by its endpoints and "
      "<code>provenance_fact_ids</code>, never by its id.</p>")
    a("</section>")

    # ---- the other graph
    a('<section class="s">')
    a("<h2>Relation to the Lateiner/Hurwitz graph</h2>")
    a('<p class="note">The project keeps two graphs over overlapping material. '
      "They are joined, not merged, and they share "
      "<b>no relation names at all</b> &mdash; the join is "
      "<code>Zylbercweig/plays/kg_crosslink.py</code>, which maps catalogue "
      "<code>work</code> ids to <code>plays_db</code> play ids and carries the "
      "ascription verdicts and open questions both ways.</p>")
    a("<table><thead><tr><th></th><th>this graph</th>"
      "<th>Lateiner/Hurwitz</th></tr></thead><tbody>")
    a(f"<tr><td>size</td><td>{_fmt(len(nodes))} nodes / {_fmt(len(edges))} "
      "edges</td><td>692 nodes / 887 edges</td></tr>")
    a(f"<tr><td>relations</td><td>{len(rels)}</td><td>17</td></tr>")
    a("<tr><td>the play unit</td><td><code>play</code></td>"
      "<td><code>work</code> + <code>edition</code></td></tr>")
    a("<tr><td>shared kinds</td><td colspan='2'><code>person</code>, "
      "<code>org</code>, <code>place</code>, <code>edition</code></td></tr>")
    a("<tr><td>only here</td><td colspan='2'><code>play</code>, "
      "<code>event</code>, <code>venue</code></td></tr>")
    a("<tr><td>only there</td><td colspan='2'><code>work</code>, "
      "<code>song</code>, <code>event</code></td></tr>")
    a("<tr><td>provenance</td><td>per-edge evidence sentence, extraction "
      "model, confidence</td><td>per-node status / method / reviewer</td></tr>")
    a("</tbody></table>")
    a(f'<p class="note">Its schema is documented on its own page: '
      f'<a href="{SISTER_URL}">the Lateiner/Hurwitz entity tree</a>, '
      "Schema tab.</p>")
    a("</section>")

    a(END)
    return "\n".join(out)


